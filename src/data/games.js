const CDN = 'https://media-rockstargames-com.akamaized.net';
/** Rockstar's CDN resizes on request — ask only for what the layout needs. */
const rs = (id, w = 1280) => `${CDN}/mfe-r19/prod/__common/img/${id}.jpg?im=Resize=(${w})`;
const tina = (path, w = 1600) => `${CDN}/tina-uploads/tina-modules/${path}.jpg?im=Resize=(${w})`;
const R6 = 'https://www.rockstargames.com/VI/_next/static/media/';
export const rockstar = (file, width = 1280) => `${R6}${file}?akim=1&imdensity=1&imwidth=${width}`;

/** Screenshot list helper: ids → { thumb, full, label, official } */
